import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import zlib from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

function sourceRecords(input, prefix, records) {
  if (!fs.existsSync(input)) return;
  const stat = fs.lstatSync(input);
  if (stat.isSymbolicLink()) throw new Error(`Game-data adapter inputs cannot be symlinks: ${input}`);
  if (stat.isDirectory()) {
    for (const name of fs.readdirSync(input).sort()) sourceRecords(path.join(input, name), `${prefix}/${name}`, records);
  } else if (stat.isFile()) {
    const hash = createHash('sha256');
    const fd = fs.openSync(input, 'r');
    const buffer = Buffer.allocUnsafe(1024 * 1024);
    try { for (let count; (count = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0;) hash.update(buffer.subarray(0, count)); }
    finally { fs.closeSync(fd); }
    records.push([prefix, stat.size, hash.digest('hex')]);
  }
}

const python = process.platform === 'win32' ? 'python' : 'python3';

function adapterSources(root) {
  const directory = path.join(root, 'data/game-data/version-adapters');
  const generator = path.join(root, 'tools/mc26-oracle/scripts/package-adapter-store.py');
  const records = [];
  sourceRecords(generator, 'store-generator', records);
  sourceRecords(directory, 'version-adapter-inputs', records);
  const versions = fs.existsSync(directory) ? [...new Set(fs.readdirSync(directory, { withFileTypes: true })
    .map(entry => entry.isFile() && entry.name.endsWith('.zip') ? entry.name.slice(0, -4) : entry.name))].sort() : [];
  return { directory, generator, records, versions };
}

// Keep the expensive store build independent of compiler/source revisions.
// A staged store is reusable only if both the inputs and generated bytes match.
export function prepareAdapterStore(root = repository, sources = adapterSources(root)) {
  if (!sources.versions.length) return null;
  const input = createHash('sha256').update(JSON.stringify(sources.records)).digest('hex');
  const cache = path.join(root, '.tmp/game-data/adapter-store');
  const directory = path.join(cache, 'version-adapters');
  const marker = path.join(cache, 'receipt.json');
  function outputs() {
    const records = [];
    for (const name of ['index.json', 'shared.zip']) sourceRecords(path.join(directory, name), name, records);
    return records;
  }
  if (fs.existsSync(marker)) {
    const receipt = JSON.parse(fs.readFileSync(marker, 'utf8'));
    if (receipt.input === input && JSON.stringify(receipt.files) === JSON.stringify(outputs()) && receipt.files.length === 2) return directory;
  }
  const result = spawnSync(python, [sources.generator, '--input', sources.directory, '--output', path.join(directory, 'shared.zip')],
    { cwd: root, stdio: 'inherit', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error(`Shared adapter build failed: ${result.error?.message || result.status}`);
  const files = outputs();
  if (files.length !== 2) throw new Error('Missing generated shared adapter index/archive.');
  fs.writeFileSync(marker, JSON.stringify({ input, files }));
  return directory;
}

export function checkBundledGameData(output, versions) {
  const expected = ['derived', 'index.json', 'manifest.json', 'resources.jar'];
  if (JSON.stringify(fs.readdirSync(output).sort()) !== JSON.stringify(expected)) {
    throw new Error('Default data staging is not JAR-only or contains unexpected files.');
  }
  if (versions.length) {
    const adapters = path.join(output, 'derived/version-adapters');
    if (JSON.stringify(fs.readdirSync(adapters).sort()) !== '["index.json","shared.zip"]') {
      throw new Error('Default data staging must contain only the indexed shared version store.');
    }
    const metadata = JSON.parse(fs.readFileSync(path.join(adapters, 'index.json'), 'utf8'));
    if (metadata.format !== 'nova.version-adapter-store' || metadata.schema_version !== 3
        || JSON.stringify(Object.keys(metadata.versions).sort()) !== JSON.stringify(versions)) {
      throw new Error('Default data staging does not include the exact source adapter set.');
    }
    const manifest = JSON.parse(fs.readFileSync(path.join(output, 'manifest.json'), 'utf8'));
    if (manifest.game_version === '26.3') {
      const supported = JSON.parse(fs.readFileSync(path.join(output, 'derived/blockdb/versions.json'), 'utf8'));
      if (JSON.stringify(supported.sort()) !== JSON.stringify([...versions, manifest.game_version].sort())) {
        throw new Error('Default data staging is missing a supported exact-version adapter.');
      }
    }
    const index = JSON.parse(fs.readFileSync(path.join(output, 'index.json'), 'utf8'));
    const prefix = 'derived/version-adapters/';
    if (Object.keys(index).filter(key => key.startsWith(prefix)).length !== 2) throw new Error('Stale logical adapter index.');
    for (const name of ['shared.zip', 'index.json']) {
      const recorded = index[prefix + name];
      const physical = [];
      sourceRecords(path.join(adapters, name), name, physical);
      if (!recorded || recorded.bytes !== physical[0]?.[1] || recorded.sha256 !== physical[0]?.[2]) {
        throw new Error(`Staged adapter does not match the generated package index: ${name}`);
      }
    }
  }
}

// The adapter inputs below are existing generated, versioned facts. Extraction,
// validation, normalization and package identity belong to the public importer.
export function prepareDefaultGameData(core, options = {}) {
  const root = options.root || repository;
  const version = options.gameVersion || '26.3';
  if (!/^[A-Za-z0-9_.-]{1,100}$/.test(version)) throw new Error('Invalid game version.');
  const output = path.resolve(options.output || path.join(root, 'pack-in/game-data/default'));
  const manifest = path.join(output, 'manifest.json');
  const jar = path.resolve(options.jar || path.join(root, 'data/mc26', version, 'client.jar'));
  if (!fs.existsSync(jar)) {
    if (options.optional && !fs.existsSync(manifest)) {
      console.log('No default game data package in this checkout. Import a client JAR in Resources before using game resources.');
      return null;
    }
    throw new Error('The default data source is missing. Restore the bundled resource archive or specify --jar; no local Minecraft installation is required.');
  }
  const inputs = [
    [`pack-in/materials/minecraft-${version}.json`, 'inventory.json'],
    ...(version === '26.3' ? [['pack-in/lang/zh_cn.json', 'lang/zh_cn.json'], ['pack-in/lang/en_us.json', 'lang/en_us.json']] : []),
    ['data/blockdb', 'blockdb'],
    [`data/mc26/${version}/oracle`, 'oracle'],
    [`pack-in/item-icons-${version}`, 'item-icons'],
    ...(version === '26.3' ? [['pack-in/game-icons/block.zip', 'block-icons.zip']] : []),
  ];
  const sources = adapterSources(root);
  if (!options.optional && !sources.versions.length) throw new Error('No official version adapter inputs.');
  const assets = options.assets || path.join(root, 'data/mc26', version, 'assets');
  const records = [...sources.records];
  sourceRecords(jar, 'source.jar', records);
  sourceRecords(assets, 'assets', records);
  sourceRecords(fileURLToPath(import.meta.url), 'prepare-script', records);
  const compactor = path.join(root, 'tools/mc26-oracle/scripts/compact-default-oracle.py');
  sourceRecords(compactor, 'oracle-compactor', records);
  sourceRecords(path.join(root, 'tools/viewer-core/src/compact_oracle.rs'), 'compact-oracle-reader', records);
  sourceRecords(path.join(root, 'tools/viewer-core/src/game_data.rs'), 'importer', records);
  sourceRecords(path.join(root, 'tools/viewer-core/src/version_adapter_store.rs'), 'store-reader', records);
  for (const [source, destination] of inputs) sourceRecords(path.join(root, source), destination, records);
  const inputId = createHash('sha256').update(JSON.stringify([2, version, records])).digest('hex');
  const marker = path.join(output, 'derived/prepare-inputs.json');
  if (!options.force && fs.existsSync(manifest) && fs.existsSync(marker)
      && JSON.parse(fs.readFileSync(manifest, 'utf8')).game_version === version
      && JSON.parse(fs.readFileSync(marker, 'utf8')).source_input_identity === inputId) {
    checkBundledGameData(output, sources.versions);
    console.log('Default game data: reusing the matching source/adapter identity (independent of AppVersion).');
    return output;
  }
  const stagingRoot = path.resolve(root, '.tmp/game-data');
  const adapter = path.resolve(stagingRoot, `default-adapter-${version}`);
  if (path.dirname(adapter) !== stagingRoot) throw new Error('Adapter staging path leaves its build directory.');
  // Only this generated staging directory is replaced: removed source tables
  // must not survive a later build with the same Minecraft version.
  fs.rmSync(adapter, { recursive: true, force: true });
  fs.mkdirSync(adapter, { recursive: true });
  fs.writeFileSync(path.join(adapter, 'adapter.json'), JSON.stringify({ game_version: version }));
  fs.writeFileSync(path.join(adapter, 'prepare-inputs.json'), JSON.stringify({ schema_version: 1, source_input_identity: inputId }));
  for (const [source, destination] of inputs) {
    const input = path.join(root, source);
    if (!fs.existsSync(input)) continue;
    const outputDir = path.join(adapter, destination);
    if (destination === 'oracle' && fs.existsSync(path.join(input, 'oracle-manifest.json'))) {
      const packed = spawnSync(python, [compactor, input, outputDir], { cwd: root, stdio: 'inherit', windowsHide: true });
      if (packed.error || packed.status !== 0) throw new Error(`Default oracle encoding failed: ${packed.error?.message || packed.status}`);
    } else {
      fs.cpSync(input, outputDir, { recursive: true });
    }
  }
  const store = prepareAdapterStore(root, sources);
  if (store) {
    fs.mkdirSync(path.join(adapter, 'version-adapters'), { recursive: true });
    for (const name of ['index.json', 'shared.zip']) {
      fs.copyFileSync(path.join(store, name), path.join(adapter, 'version-adapters', name));
    }
  }
  const blocksFile = path.join(adapter, 'blockdb/blocks.dat.z');
  if (fs.existsSync(blocksFile)) {
    const blocks = zlib.inflateSync(fs.readFileSync(blocksFile));
    const marker = blocks.lastIndexOf(Buffer.from('NOVAST04'));
    if (marker < 0) throw new Error('The existing version registry has no canonical adapter supplement.');
    const length = blocks.readUInt32LE(marker + 8);
    const supplement = JSON.parse(zlib.inflateSync(blocks.subarray(marker + 12, marker + 12 + length)));
    fs.writeFileSync(path.join(adapter, 'blockdb/versions.json'), JSON.stringify(Object.keys(supplement.versions).sort()));
  }
  const args = ['game-data', 'build-default', '--jar', jar, '--output', output, '--game-version', version, '--adapter-dir', adapter];
  if (fs.existsSync(assets)) args.push('--assets-dir', path.resolve(assets));
  const result = spawnSync(core, args, { cwd: root, stdio: 'inherit', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error(`Default game data import failed: ${result.error?.message || result.status}`);
  if (!fs.existsSync(manifest)) throw new Error('The common importer did not produce a complete default package.');
  checkBundledGameData(output, sources.versions);
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const value = name => { const i = args.indexOf(name); return i < 0 ? undefined : args[i + 1]; };
  try {
    const core = path.resolve(value('--core') || path.join(repository, 'bin/public-beta', process.platform === 'win32' ? 'litematica_core.exe' : 'litematica_core'));
    prepareDefaultGameData(core, { gameVersion: value('--game-version'), jar: value('--jar'), assets: value('--assets-dir'), output: value('--output'), force: args.includes('--force'), optional: args.includes('--optional') });
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
